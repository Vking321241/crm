export type ConversationStatus = 'open' | 'pending' | 'closed';

export interface Conversation {
  id: string;
  user_id: string;
  contact_id: string;
  status: ConversationStatus;
  assigned_agent_id?: string;
  department_id?: string | null;
  last_message_text?: string;
  last_message_at?: string;
  unread_count: number;
  created_at: string;
  updated_at: string;
  contact?: Contact;
  /**
   * AI auto-reply state for this thread (migration 029 + 033):
   *  - `ai_autoreply_disabled` — the bot is paused here (a human took
   *    over, or the model handed off). Sticky until re-enabled.
   *  - `ai_reply_count` — how many times the bot has auto-replied,
   *    checked against the account's per-conversation cap.
   *  - `ai_handoff_summary` — short internal note the bot wrote when it
   *    handed off, shown to whoever takes the thread over.
   */
  ai_autoreply_disabled?: boolean;
  ai_reply_count?: number;
  ai_handoff_summary?: string | null;
  /** The contact's product/service tags — e.g. [Setor Gráfico],
   *  [Fardamentos] — shown as colored chips in the conversation list. */
  tags?: Tag[];
  /** True when the current assignee hasn't confirmed starting service
   *  after a transfer or a business-hours auto-resume — drives the
   *  "iniciar atendimento / apenas visualizar" pop-up. */
  needs_acknowledgment?: boolean;
  acknowledgment_reason?: "transferred" | "resumed";
  paused_at?: string;
  pause_reason?: "manual" | "business_hours";
}

